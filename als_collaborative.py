def build_interaction_matrix(df, n_users, n_items):
    if df.shape[0] == 0:
        return sparse.csr_matrix((n_users, n_items), dtype=np.float32)
    vals = df['rating'].cast(pl.Float32).to_numpy()
    user_indices = df['user_idx'].to_numpy()
    item_indices = df['item_idx'].to_numpy()
    return sparse.csr_matrix(
        (vals, (user_indices, item_indices)),
        shape=(n_users, n_items)
    )

