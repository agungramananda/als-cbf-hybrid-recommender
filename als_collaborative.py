class PopularityRecommender:
    def __init__(self, train_matrix):
        # Calculate item popularity (number of interactions in train set)
        self.item_popularity = np.array(train_matrix.sum(axis=0)).flatten()
        # Sort items by popularity descending
        self.sorted_items = np.argsort(-self.item_popularity)
        self.sorted_scores = self.item_popularity[self.sorted_items]

    def recommend(self, userid, user_items, N=10, filter_already_liked_items=True, **kwargs):
        # Handle single user or multiple users
        is_scalar = np.isscalar(userid)
        users = [userid] if is_scalar else userid

        batch_recs = []
        batch_scores = []

        for i, u in enumerate(users):
            # user_items is a batch corresponding to the users array, so we index by i, not u
            liked = set(user_items[i].indices) if filter_already_liked_items and user_items is not None else set()
            recs = []
            scores = []
            for item, score in zip(self.sorted_items, self.sorted_scores):
                if item not in liked:
                    recs.append(item)
                    scores.append(score)
                    if len(recs) == N:
                        break
            batch_recs.append(recs)
            batch_scores.append(scores)

        if is_scalar:
            return np.array(batch_recs[0], dtype=np.int32), np.array(batch_scores[0], dtype=np.float32)
        return np.array(batch_recs, dtype=np.int32), np.array(batch_scores, dtype=np.float32)

