K_VALUES = [10]
NUM_THREADS = 0

def evaluate_metrics(model, train_matrix, eval_matrix, K=10, batch_size=1000):
    eval_users = np.unique(eval_matrix.tocoo().row)
    if len(eval_users) == 0:
        return 0.0, 0.0, 0.0
    
    precisions = []
    recalls = []
    ndcgs = []
    
    for i in range(0, len(eval_users), batch_size):
        batch_users = eval_users[i:i+batch_size]
        
        # Get recommendations
        ids, _ = model.recommend(
            batch_users,
            train_matrix[batch_users],
            N=K,
            filter_already_liked_items=True
        )
        
        for idx, user in enumerate(batch_users):
            start_idx = eval_matrix.indptr[user]
            end_idx = eval_matrix.indptr[user + 1]
            true_items = set(eval_matrix.indices[start_idx:end_idx])
            
            if len(true_items) == 0:
                continue
                
            rec_items = ids[idx]
            
            hits = 0
            dcg = 0.0
            for rank, item in enumerate(rec_items):
                if item in true_items:
                    hits += 1
                    dcg += 1.0 / np.log2(rank + 2)
            
            idcg = sum(1.0 / np.log2(r + 2) for r in range(min(K, len(true_items))))
            ndcg = dcg / idcg if idcg > 0 else 0.0
            
            precision = hits / K
            recall = hits / len(true_items)
            
            precisions.append(precision)
            recalls.append(recall)
            ndcgs.append(ndcg)
            
    return np.mean(precisions), np.mean(recalls), np.mean(ndcgs)

def evaluate_model(model, train_items, eval_items, label='', k_values=K_VALUES, verbose=True):
    metrics = {}
    if verbose:
        print(f'\n--- {label} ---')
    for k in k_values:
        p, r, n = evaluate_metrics(model, train_items, eval_items, K=k)
        metrics[f'Prec@{k}'] = p
        metrics[f'Recall@{k}'] = r
        metrics[f'NDCG@{k}'] = n
        if verbose:
            print(f'  K={k:>2}  Prec@{k}: {p:.6f}  Recall@{k}: {r:.6f}  NDCG@{k}: {n:.6f}')
    return metrics

